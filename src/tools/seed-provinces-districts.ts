// ─── Main Seed ───────────────────────────────────────────────

async function seedProvincesAndDistricts(): Promise<void> {
  console.log('\n🌍 G1 — Seeding Provinces, Districts, MafhoomDistrictRouting...\n');
  console.log(`   📊 Total entries: ${ROUTING_DATA.length}`);

  // 1. Check for duplicates in data
  const seen = new Set<string>();
  for (const r of ROUTING_DATA) {
    const key = `${r.p}::${r.d}`;
    if (seen.has(key)) {
      throw new Error(`Duplicate district in data: "${r.d}" in province "${r.p}"`);
    }
    seen.add(key);
  }

  // 2. Seed Provinces (upsert by name)
  const uniqueProvinces = [...new Set(ROUTING_DATA.map(r => r.p))];
  console.log(`   🏛️  Provinces: ${uniqueProvinces.length}`);

  const provinceMap = new Map<string, number>();
  for (const name of uniqueProvinces) {
    const province = await prisma.province.upsert({
      where: { name },
      update: {},
      create: { name },
    });
    provinceMap.set(name, province.id);
  }

  // 3. Seed Districts (upsert by provinceId + name)
  console.log(`   🏘️  Districts: ${ROUTING_DATA.length}`);

  const districtMap = new Map<string, number>();
  for (const r of ROUTING_DATA) {
    const provinceId = provinceMap.get(r.p)!;
    const district = await prisma.district.upsert({
      where: { provinceId_name: { provinceId, name: r.d } },
      update: {},
      create: { provinceId, name: r.d },
    });
    districtMap.set(`${r.p}::${r.d}`, district.id);
  }

  // 4. Seed MafhoomDistrictRouting (upsert by districtId)
  let countA = 0;
  let countB = 0;
  for (const r of ROUTING_DATA) {
    const districtId = districtMap.get(`${r.p}::${r.d}`)!;
    await prisma.mafhoomDistrictRouting.upsert({
      where: { districtId },
      update: { targetSection: r.t },
      create: { districtId, targetSection: r.t },
    });
    if (r.t === 'أ') countA++;
    if (r.t === 'ب') countB++;
  }

  // 5. Validation
  console.log('\n   ✅ Validation:');

  const dbProvinces = await prisma.province.count();
  const dbDistricts = await prisma.district.count();
  const dbRoutingA = await prisma.mafhoomDistrictRouting.count({ where: { targetSection: 'أ' } });
  const dbRoutingB = await prisma.mafhoomDistrictRouting.count({ where: { targetSection: 'ب' } });
  const dbRoutingTotal = await prisma.mafhoomDistrictRouting.count();
  const districtsWithoutRouting = await prisma.district.count({ where: { routing: null } });

  const checks = [
    { name: 'Provinces', expected: 22, actual: dbProvinces },
    { name: 'Districts', expected: 333, actual: dbDistricts },
    { name: 'Routing أ', expected: 114, actual: dbRoutingA },
    { name: 'Routing ب', expected: 219, actual: dbRoutingB },
    { name: 'Total Routing', expected: 333, actual: dbRoutingTotal },
    { name: 'Districts without routing', expected: 0, actual: districtsWithoutRouting },
  ];

  let allPassed = true;
  for (const c of checks) {
    const status = c.actual === c.expected ? '✅ PASS' : '❌ FAIL';
    if (c.actual !== c.expected) allPassed = false;
    console.log(`      ${status} — ${c.name}: ${c.actual} (expected ${c.expected})`);
  }

  if (!allPassed) {
    console.log('\n   ❌ G1 SEED VALIDATION FAILED\n');
    process.exit(1);
  }

  console.log('\n   🎉 G1 Seed completed successfully!\n');
}

// ─── Run ─────────────────────────────────────────────────────

seedProvincesAndDistricts()
  .catch((e) => {
    console.error('❌ Seed error:', e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
